"""Password login for the dashboard: scrypt password hash, HMAC-signed session cookie, login rate limit.

Settings in /opt/t2/.env (set with infra/set_dashboard_password.sh, never typed into chat):
  DASHBOARD_PASSWORD_HASH  scrypt$<n>$<r>$<p>$<salt hex>$<hash hex>
  DASHBOARD_SESSION_KEY    random secret that signs session cookies (generated by deploy_services.sh)
"""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets
import time
from collections import defaultdict, deque

COOKIE = "t2_session"
SESSION_SECONDS = 7 * 24 * 3600
N, R, P = 2**14, 8, 1
MAX_FAILURES = 5  # per client per 15 minutes
WINDOW = 15 * 60

_failures: dict[str, deque[float]] = defaultdict(deque)


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode(), salt=salt, n=N, r=R, p=P, dklen=32)
    return f"scrypt${N}${R}${P}${salt.hex()}${digest.hex()}"


def check_password(password: str, stored: str) -> bool:
    try:
        algo, n, r, p, salt, digest = stored.split("$")
        if algo != "scrypt":
            return False
        got = hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=int(n), r=int(r), p=int(p), dklen=32)
        return hmac.compare_digest(got.hex(), digest)
    except (ValueError, TypeError):
        return False


def _key() -> bytes:
    key = os.environ.get("DASHBOARD_SESSION_KEY", "")
    if len(key) < 32:
        raise RuntimeError("DASHBOARD_SESSION_KEY is missing")
    return key.encode()


def make_session(now: float | None = None) -> str:
    expires = int((now or time.time()) + SESSION_SECONDS)
    payload = f"{expires}.{secrets.token_hex(8)}"
    sig = hmac.new(_key(), payload.encode(), hashlib.sha256).hexdigest()
    return f"{payload}.{sig}"


def valid_session(token: str | None, now: float | None = None) -> bool:
    if not token or token.count(".") != 2:
        return False
    expires, nonce, sig = token.split(".")
    try:
        good = hmac.compare_digest(sig, hmac.new(_key(), f"{expires}.{nonce}".encode(), hashlib.sha256).hexdigest())
        return good and int(expires) > (now or time.time())
    except (ValueError, RuntimeError):
        return False


def allowed_attempt(client: str, now: float | None = None) -> bool:
    now = now or time.time()
    q = _failures[client]
    while q and now - q[0] > WINDOW:
        q.popleft()
    return len(q) < MAX_FAILURES


def record_failure(client: str, now: float | None = None) -> None:
    _failures[client].append(now or time.time())


def configured() -> bool:
    return bool(os.environ.get("DASHBOARD_PASSWORD_HASH")) and len(os.environ.get("DASHBOARD_SESSION_KEY", "")) >= 32
